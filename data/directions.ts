/**
 * Направления школы — единственное место, где они описаны.
 * Отсюда берут карточки страницы «Направления», блок «Что хочется танцевать
 * тебе?» на главной и страницы каждого стиля (/directions/<slug>).
 * Тексты — из прототипа владельца, обращение на «ты».
 */

/** Фотография направления (файлы лежат в public/directions, квадрат). */
export type StylePhoto = { src: string; alt: string };

export type FaqItem = { question: string; answer: string };

export type DanceStyle = {
  /** Адрес страницы: /directions/<slug>. */
  slug: string;
  /** Полное название — заголовок страницы стиля и карточки на главной. */
  title: string;
  /** Короткое имя для подписи кнопок и сообщений. */
  short: string;
  /** Три слова над названием на карточке. */
  tags: string[];
  /** Описание на карточке и под заголовком страницы стиля. */
  description: string;
  /** Крупный заголовок страницы стиля, по строке на элемент. */
  hero: string[];
  /** «Кому подойдёт». */
  who: string;
  /** «Чем будем заниматься» — три пункта. */
  learn: { title: string; text: string }[];
  /** Вопросы на странице стиля. */
  faq: FaqItem[];
  /** Фото — только у бачаты; у дэнсхолла и латины своё оформление. */
  photo?: StylePhoto;
  /** Карточка на странице «Направления»: подпись и крупное слово. */
  card: {
    variant: "card-large" | "card-pink" | "card-dark" | "card-outline";
    number: string;
    kicker: string;
    title: string;
  };
};

