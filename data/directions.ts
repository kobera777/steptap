/**
 * Направления школы — единственное место, где они описаны.
 * Отсюда берут карточки страницы «Направления», блок «Что хочется танцевать
 * тебе?» на главной. Отдельных страниц у стилей нет — всё на одной странице.
 * Тексты — из прототипа владельца, обращение на «ты».
 */

/** Фотография направления (файлы лежат в public/directions, квадрат). */
export type StylePhoto = { src: string; alt: string };

export type FaqItem = { question: string; answer: string };

export type DanceStyle = {
  /** Идентификатор стиля (ключ, класс оформления). */
  slug: string;
  /** Полное название стиля. */
  title: string;
  /** Три слова над названием на карточке. */
  tags: string[];
  /** Описание на карточке. */
  description: string;
  /** Фото — только у бачаты; у дэнсхолла и латины своё оформление. */
  photo?: StylePhoto;
  /** Карточка на странице «Направления»: подпись и крупное слово. */
  card: {
    variant: "card-large" | "card-pink" | "card-dark" | "card-outline";
    number: string;
    kicker: string;
    title: string;
  };
};

